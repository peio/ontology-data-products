"""Check the optional bridge from ontology 2.0.0 to the FIBO variant.

Usage: python scripts/check_bridge.py   (run from the project root, after the main and
FIBO pipelines). Applies queries/bridge-revenue.rq to the 2.0.0 data, reasons with
OWL RL, runs the ASK checks in queries/bridge-tests.rq, then asks the FIBO variant's
Track B questions of the bridged 2.0.0 data. Writes reports/bridge-check.md.
Exits 1 if any check fails.
"""
import csv
import sys
from datetime import date
from pathlib import Path

import owlrl
from rdflib import Graph

from run_tests import ROOT, fmt, load, sections

ONT = ROOT / "ontology"
BRIDGE = ONT / "estx50-fibo-bridge.ttl"
TBOX = [ONT / "estx50-ontology.ttl", ONT / "icb-skos.ttl", BRIDGE, ONT / "estx50-fibo-ontology.ttl",
        ONT / "fibo-extract.ttl", ONT / "icb-fibo-alignment.ttl"]
DATA_2 = ROOT / "data" / "estx50-instances.ttl"
DATA_FIBO = ROOT / "data" / "estx50-fibo-instances.ttl"
RULE = ROOT / "queries" / "bridge-revenue.rq"

# FIBO Track B questions the bridged 2.0.0 data can answer, and those it cannot:
# B3 and B4 read LCC country names, but 2.0.0 countries stay Wikidata IRIs.
ANSWERABLE = {"B1", "B2", "B5", "B6"}
NOT_ANSWERABLE = {"B3": "needs LCC countries; 2.0.0 uses Wikidata IRIs",
                  "B4": "needs LCC countries; 2.0.0 uses Wikidata IRIs"}


def reasoned(g: Graph) -> Graph:
    r = Graph()
    for t in g:
        r.add(t)
    owlrl.DeductiveClosure(owlrl.OWLRL_Semantics).expand(r)
    return r


def main() -> int:
    base = load(*TBOX, DATA_2)
    converted = base.query(RULE.read_text(encoding="utf-8")).graph
    for t in converted:
        base.add(t)
    bridged = reasoned(base)
    both = load(*TBOX, DATA_2, DATA_FIBO)
    for t in converted:
        both.add(t)
    both = reasoned(both)
    graphs = {"bridge": load(BRIDGE), "bridged": bridged, "both": both}

    results_a = []
    for (tid, gname, desc), q in sections(ROOT / "queries" / "bridge-tests.rq", "test"):
        ok = bool(graphs[gname].query(q).askAnswer)
        results_a.append((tid, desc, ok, f"ASK on {gname} graph"))

    key = {}
    for r in csv.DictReader(open(ROOT / "queries" / "answer-key-fibo.csv", encoding="utf-8")):
        key.setdefault(r["query"], []).append((r["key"], r["value"]))
    results_b = []
    for (qid, question), q in sections(ROOT / "queries" / "business-queries-fibo.rq", "query"):
        got = [(fmt(row[0]), "|".join(fmt(v) for v in row[1:])) for row in bridged.query(q)]
        if qid in ANSWERABLE:
            ok, expected = sorted(got) == sorted(key.get(qid, [])), "same as answer-key-fibo.csv"
        else:
            ok, expected = not got, f"no rows ({NOT_ANSWERABLE[qid]})"
        results_b.append((qid, question, ok, len(got), expected))

    a_pass = sum(r[2] for r in results_a)
    b_pass = sum(r[2] for r in results_b)
    lines = [
        "# Bridge check: 2.0.0 data read in FIBO terms",
        "",
        f"Generated by `scripts/check_bridge.py` on {date.today().isoformat()}.",
        "",
        f"**Bridge checks: {a_pass}/{len(results_a)} passed. "
        f"FIBO Track B on bridged 2.0.0 data: {b_pass}/{len(results_b)} as expected.**",
        "",
        f"The revenue rule (`queries/bridge-revenue.rq`) added {len(converted)} triples. "
        f"Graph sizes after OWL RL: bridged {len(bridged)} triples; with the FIBO variant's data too, {len(both)}.",
        "",
        "## Bridge checks",
        "",
        "| Test | Check | Result | Detail |",
        "| --- | --- | --- | --- |",
    ]
    for tid, desc, ok, detail in sorted(results_a):
        lines.append(f"| {tid} | {desc} | {'PASS' if ok else 'FAIL'} | {detail} |")
    lines += ["", "## FIBO Track B on bridged 2.0.0 data", "",
              "| Query | Question | Result | Rows | Expected |", "| --- | --- | --- | --- | --- |"]
    for qid, question, ok, n, expected in results_b:
        lines.append(f"| {qid} | {question} | {'PASS' if ok else 'FAIL'} | {n} | {expected} |")
    lines.append("")
    (ROOT / "reports" / "bridge-check.md").write_text("\n".join(lines), encoding="utf-8")

    for tid, desc, ok, detail in sorted(results_a):
        print(f"{'PASS' if ok else 'FAIL'}  {tid}  {desc}  [{detail}]")
    for qid, question, ok, n, expected in results_b:
        print(f"{'PASS' if ok else 'FAIL'}  {qid}  {question}  [{n} rows; expected {expected}]")
    print(f"\nBridge {a_pass}/{len(results_a)}, Track B {b_pass}/{len(results_b)}")
    return 0 if a_pass == len(results_a) and b_pass == len(results_b) else 1


if __name__ == "__main__":
    sys.exit(main())
